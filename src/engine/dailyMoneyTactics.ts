/**
 * 일진 기반 시간대별 금전 행동 비책 산출 함수
 */
export function getDailyTimeSlotMoneyTactics(
  selectedDate: Date,
  godName?: string,
  isJa: boolean = false
): DailyMoneyTacticsResult {
  // 기본 키워드 매핑 (없을 시 일자의 요일/일자 해시를 통해 동적 분기)
  let key = godName || '';
  if (!TACTICS_MATRIX[key]) {
    const keys = Object.keys(TACTICS_MATRIX);
    const daySeed = (selectedDate.getFullYear() * 1000 + (selectedDate.getMonth() + 1) * 31 + selectedDate.getDate()) % keys.length;
    key = keys[daySeed] ?? '정재';
  }

  const preset = TACTICS_MATRIX[key] || TACTICS_MATRIX['정재'];

  const morningSlot = isJa ? '[午前 09〜12時 (巳・午の刻)]' : '[오전 09~12시 (巳·午시)]';
  const afternoonSlot = isJa ? '[午後 13〜17時 (未・申の刻)]' : '[오후 13~17시 (未·申시)]';
  const eveningSlot = isJa ? '[夜間 18〜22時 (酉・戌の刻)]' : '[저녁 18~22시 (酉·戌시)]';

  return {
    morning: {
      hourLabel: morningSlot,
      desc: isJa ? preset.morning.jp : preset.morning.kr,
    },
    afternoon: {
      hourLabel: afternoonSlot,
      desc: isJa ? preset.afternoon.jp : preset.afternoon.kr,
    },
    evening: {
      hourLabel: eveningSlot,
      desc: isJa ? preset.evening.jp : preset.evening.kr,
    },
  };
}
